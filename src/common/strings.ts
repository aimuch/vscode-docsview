export type StringKey = keyof typeof en;
export type Lang = 'en' | 'zh';

const tables: Record<Lang, typeof en> = { en, zh };

export function translate(lang: Lang, key: StringKey, ...args: (string | number)[]): string {
  return tables[lang][key].replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}

export function pickLang(locale: string | undefined): Lang {
  return locale?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
